  /// Solicitud vigente: el detalle del backend si ya respondió, y mientras
  /// tanto lo que trajo la agenda.
  Map<String, dynamic>? get _request =>
      _model.detail ?? DHASSOCIATETuTrabajoWidget.requestData;

  /// Trae el detalle completo de la visita. Es la lectura que revela la
  /// dirección exacta y las instrucciones de ingreso: el listado del
  /// marketplace sólo expone la zona, porque ahí el trabajo todavía no era de
  /// nadie.
  Future<void> _loadDetail() async {
    final data = DHASSOCIATETuTrabajoWidget.requestData;
    final id = data == null ? '' : asrId(data);
    if (id.isEmpty) return;

    try {
      final response = await DOVIAAPIDoviaHomeContextGroup
          .getAssociateServiceRequestCall
          .call(
        serviceRequestId: id,
        authToken: currentAuthenticationToken ?? '',
      );
      if (!mounted || !response.succeeded) return;

      final detail = getJsonField(response.jsonBody, r'''$.data''');
      if (detail is! Map) return;

      safeSetState(() {
        _model.detail = Map<String, dynamic>.from(detail);
        _fillVisitFields();
      });
    } catch (_) {
      // Sin detalle la pantalla queda con los campos vacíos y su hint; no se
      // rompe la navegación por un fallo de red.
    }
  }

  /// Vuelca la dirección exacta y las instrucciones de ingreso en los campos de
  /// la pantalla. No pisa lo que el asociado haya escrito a mano.
  void _fillVisitFields() {
    final data = _request;
    if (data == null) return;

    final address = asrExactAddress(data);
    if (address != null && (_model.textController1?.text ?? '').isEmpty) {
      _model.textController1?.text = address;
    }

    final instructions = asrAccessInstructions(data);
    if (instructions != null && (_model.textController2?.text ?? '').isEmpty) {
      _model.textController2?.text = instructions;
    }
  }

  /// Centro por defecto del mapa: Ciudad de Guatemala, el mismo fallback que
  /// usa el selector de dirección del cliente. Sólo se usa si la solicitud
  /// todavía no trae coordenadas propias.
  static const double _kDefaultLat = 14.634915;
  static const double _kDefaultLng = -90.506882;

  double get _mapLatitude {
    final data = _request;
    return (data == null ? null : asrLatitude(data)) ?? _kDefaultLat;
  }

  double get _mapLongitude {
    final data = _request;
    return (data == null ? null : asrLongitude(data)) ?? _kDefaultLng;
  }

  /// Ubicación GPS actual del asociado para el check-in. El backend verifica
  /// con esto que esté en el radio del domicilio antes de avisarle al
  /// cliente, así que sin coordenadas el check-in no se manda: se le pide el
  /// permiso de ubicación en el momento en vez de asumirlo concedido.
  Future<Position?> _captureCurrentPosition() async {
    if (!await Geolocator.isLocationServiceEnabled()) {
      _showMessage(
          'Activá la ubicación del dispositivo para notificar tu llegada.');
      return null;
    }

    var permission = await Geolocator.checkPermission();
    if (permission == LocationPermission.denied) {
      permission = await Geolocator.requestPermission();
    }
    if (permission == LocationPermission.denied ||
        permission == LocationPermission.deniedForever) {
      _showMessage(
          'Necesitamos permiso de ubicación para notificar tu llegada.');
      return null;
    }

    try {
      return await Geolocator.getCurrentPosition(
        locationSettings: const LocationSettings(
          accuracy: LocationAccuracy.high,
          timeLimit: Duration(seconds: 15),
        ),
      );
    } catch (_) {
      _showMessage('No pudimos obtener tu ubicación. Intentá de nuevo.');
      return null;
    }
  }

  /// Notifica que el asociado llegó al punto y arranca el trabajo
  /// (`POST .../start`): la solicitud pasa de `TAKEN` a `IN_PROGRESS`
  /// ("En Sitio") y el backend le dispara al cliente el push de que el
  /// técnico está en la puerta.
  Future<void> _startWork() async {
    final data = _request;
    final id = data == null ? '' : asrId(data);
    if (id.isEmpty) {
      _showMessage('No se encontró el trabajo a iniciar.');
      return;
    }

    safeSetState(() => _model.isStarting = true);
    try {
      final position = await _captureCurrentPosition();
      if (position == null) return;

      final response =
          await DOVIAAPIDoviaHomeContextGroup.startServiceRequestCall.call(
        serviceRequestId: id,
        latitude: position.latitude,
        longitude: position.longitude,
        authToken: currentAuthenticationToken ?? '',
      );
      if (!mounted) return;

      if (!response.succeeded) {
        _showMessage('No se pudo notificar tu llegada. Intenta de nuevo.');
        return;
      }

      // El trabajo ya está en curso: la pantalla de cierre opera sobre la misma
      // solicitud, así que se le pasa el detalle que ya tenemos en mano.
      DHASSOCIATETrabajoFinalizadoWidget.requestData = data;
      _showMessage('Le avisamos al cliente que ya llegaste.');
      context.pushNamed(DHASSOCIATETrabajoFinalizadoWidget.routeName);
    } finally {
      if (mounted) safeSetState(() => _model.isStarting = false);
    }
  }

  void _showMessage(String message) {
    ScaffoldMessenger.of(context).showSnackBar(
      SnackBar(content: Text(message)),
    );
  }

